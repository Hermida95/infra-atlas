import data from "@/data/graph.json";

export type PartKind = "os" | "pkg" | "code" | "meta" | "rw";
export type Part = { name: string; kind: PartKind | null; text: string };
export type Vec3 = [number, number, number];

export type GraphNode = {
  id: string;
  title: string;
  type: string;
  domain: string;
  hub: boolean;
  summary: string;
  logo: string | null;
  monogram: string | null;
  level: string;
  access: string;
  lead: string | null;
  parts: Part[];
  lab: string | null;
  position: Vec3;
};

export type Domain = { id: string; name: string; order: number; position: Vec3; hue: number };
export type Link = { source: string; target: string; type: string };
export type Graph = {
  version: number;
  generatedAt: string;
  domains: Domain[];
  nodes: GraphNode[];
  links: Link[];
};

// graph.json is generated by `uv run brain graph` from /content. Never edit it by hand.
export const graph = data as unknown as Graph;

export const nodeById = new Map(graph.nodes.map((n) => [n.id, n]));
export const domainById = new Map(graph.domains.map((d) => [d.id, d]));

export const neighbours = new Map<string, Set<string>>(graph.nodes.map((n) => [n.id, new Set()]));
for (const l of graph.links) {
  neighbours.get(l.source)?.add(l.target);
  neighbours.get(l.target)?.add(l.source);
}
