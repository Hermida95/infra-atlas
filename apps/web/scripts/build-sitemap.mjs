// Writes public/sitemap.xml from the generated graphs, the same list the App Router's sitemap.ts
// used to return. It is a script and not a route because of `output: "export"`: a metadata route
// has to declare `dynamic = "force-static"` to be exported, and Cache Components rejects that
// option. A file in public/ is the identical output with no route involved.
import fs from "node:fs";

if (!fs.existsSync("src/data/graph.json")) {
  console.error("src/data/graph.json is missing. Run `make content` (uv run brain graph) from the repo root first.");
  process.exit(1);
}
const graph = JSON.parse(fs.readFileSync("src/data/graph.json", "utf8"));

// Absolute URLs need the public origin; set NEXT_PUBLIC_SITE_URL once the site is deployed.
const site = (process.env.NEXT_PUBLIC_SITE_URL ?? "http://localhost:3000").replace(/\/+$/, "");
const escape = (value) => value.replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`);

// One file per atlas, each generated by `brain graph --content content/<id>`. The route is the
// world's own id (content/k8s -> /k8s), so nothing here has to be told the names of the worlds.
const ATLAS_FILES = ["src/data/aws.json", "src/data/k8s.json"];
const atlases = ATLAS_FILES.filter((f) => fs.existsSync(f))
  .map((f) => JSON.parse(fs.readFileSync(f, "utf8")))
  .filter((a) => a.world);

const urls = [
  { loc: `${site}/`, priority: "1.0" },
  // An atlas is one page, plus a page per node, plus one linkable view per case.
  ...atlases.flatMap((atlas) => [
    { loc: `${site}/${atlas.world.id}/`, priority: "0.9" },
    ...atlas.nodes.map((node) => ({
      loc: `${site}/${atlas.world.id}/${node.id}/`,
      priority: node.hub ? "0.7" : "0.5",
    })),
    ...atlas.cases.map((c) => ({ loc: `${site}/${atlas.world.id}/?case=${c.id}`, priority: "0.6" })),
  ]),
  ...graph.nodes.map((node) => ({ loc: `${site}/c/${node.id}/`, priority: node.hub ? "0.8" : "0.5" })),
];

const body = urls
  .map(({ loc, priority }) => `  <url>\n    <loc>${escape(loc)}</loc>\n    <priority>${priority}</priority>\n  </url>`)
  .join("\n");

fs.writeFileSync(
  "public/sitemap.xml",
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</urlset>\n`,
);
console.log(`sitemap: ${urls.length} urls`);
